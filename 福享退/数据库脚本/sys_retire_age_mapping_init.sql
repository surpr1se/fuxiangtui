-- ==============================================

-- 1. 建表
DROP TABLE IF EXISTS `sys_retire_age_mapping`;
CREATE TABLE `sys_retire_age_mapping` (
  `id` bigint NOT NULL AUTO_INCREMENT COMMENT '主键ID',
  `person_type` tinyint NOT NULL COMMENT '人员类别：11=男职工，12=女干部55岁，13=女工人50岁',
  `birth_year` int NOT NULL COMMENT '出生年份',
  `birth_month` int NOT NULL DEFAULT 0 COMMENT '出生月份：0=全年通用，1-12=具体月份',
  `original_retire_age` int NOT NULL COMMENT '原法定退休年龄（岁）',
  `reform_retire_age_year` int NOT NULL COMMENT '改革后退休年龄（年）',
  `reform_retire_age_month` int NOT NULL DEFAULT 0 COMMENT '改革后退休年龄（月）',
  `delay_months` int NOT NULL COMMENT '延迟月数',
  `create_time` datetime NOT NULL DEFAULT CURRENT_TIMESTAMP COMMENT '创建时间',
  `update_time` datetime NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP COMMENT '更新时间',
  PRIMARY KEY (`id`),
  UNIQUE KEY `uk_type_year_month` (`person_type`, `birth_year`, `birth_month`),
  KEY `idx_person_type` (`person_type`),
  KEY `idx_birth_year` (`birth_year`)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COMMENT='延迟法定退休年龄对照表';

