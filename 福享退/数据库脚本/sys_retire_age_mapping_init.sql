SELECT 
  CASE person_type 
    WHEN 11 THEN '男职工' 
    WHEN 12 THEN '女干部' 
    WHEN 13 THEN '女工人' 
  END AS 人员类型,
  COUNT(*) AS 数据条数,
  MIN(birth_year) AS 起始年份,
  MAX(birth_year) AS 结束年份
FROM sys_retire_age_mapping
GROUP BY person_type;

